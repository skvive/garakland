import assert from 'node:assert/strict';
import {parseCsv,csvExport,seedFromSignboard,validateCandidates,placeCandidateDraft,prepareRegistryDraft,normalizeName} from '../indoor/tenant-onboarding.mjs';
import {template,validateLayout} from '../indoor/layout-schema.mjs';
const seed=seedFromSignboard();
assert.equal(seed.length,14);
assert.ok(seed.every(x=>x.room===''&&x.coordinate_status==='unverified'));
assert.ok(seed.some(x=>x.name==='돌고래'));
const original=validateCandidates(seed);
assert.equal(original.ok,true,original.errors.join('\n'));
assert.equal(original.stats.signboardMatches,14);
assert.equal(original.stats.noRoom,14);
assert.equal(original.rows[0].presence_status,'photo-name-only');
assert.equal(normalizeName('이디야 가락몰점'),normalizeName(' 이디야-가락몰점 '));
const csv=csvExport(seed);
const parsed=parseCsv(csv);
assert.equal(parsed.length,14);
assert.equal(parsed[7].name,seed[7].name);
assert.ok(csv.startsWith('\uFEFF'));
assert.deepEqual(parseCsv('shop_id,name,hall,floor,room,category,source_ref\n"01","쉼,커피","5","1F","A-24","food","signed"\n')[0],
 {shop_id:'01',name:'쉼,커피',hall:'5',floor:'1F',room:'A-24',category:'food',source_ref:'signed'});
assert.equal(parseCsv('shop_id,name,hall,floor,room,category,source_ref\n"01","따옴표 "" 테스트","5","1F","","food","signed"')[0].name,'따옴표 " 테스트');
assert.throws(()=>parseCsv('a,b\n"x,y'),/닫히지/);
assert.throws(()=>parseCsv('a,b\nx,y'),/필수 헤더/);
assert.throws(()=>parseCsv('shop_id,name,hall,floor,room,category,source_ref\ns,n,5'),/열 개수/);
assert.throws(()=>parseCsv('s'.repeat(1048577)),/1MB/);
const duplicate=seed.concat([{...seed[0],shop_id:'other-id'}]);
const dup=validateCandidates(duplicate);
assert.equal(dup.ok,false);
assert.ok(dup.duplicates.some(s=>s.includes('이름·관·층')));
const conflictingRoom=validateCandidates([
 {...seed[0],room:'A-1'}, {...seed[1],room:'A-1'}]);
assert.ok(conflictingRoom.duplicates.some(s=>s.includes('호실 중복')));
const unknown=validateCandidates([{...seed[0],name:'검증하지 않은 새 매장',room:'101'}]);
assert.equal(unknown.rows[0].signboard_match,false);
assert.equal(unknown.rows[0].presence_status,'unconfirmed');
const invalid=validateCandidates([{...seed[0],hall:'9'}]);
assert.equal(invalid.ok,false);
assert.throws(()=>prepareRegistryDraft(invalid),/오류/);
const formula=csvExport([{shop_id:'s',name:'=1+2',hall:'5',floor:'1F',room:'',category:'food',source_ref:'@evil'}]);
assert.ok(formula.includes("'=1+2"));
assert.ok(formula.includes("'@evil"));
let layout=structuredClone(template);
layout.hall='5';layout.floor='3F';
const mapped=placeCandidateDraft(layout,original.rows.find(r=>r.shop_id==='h5-dolgorae'),[20,30]);
assert.equal(mapped.source.status,'draft');
assert.equal(mapped.shops.length,1);
assert.equal(mapped.shops[0].verified,false);
assert.equal(mapped.shops[0].coordinateStatus,'unverified');
assert.equal(mapped.shops[0].registryId,'h5-dolgorae');
assert.equal(validateLayout(mapped).canPublish,false);
assert.equal(layout.shops.length,0,'input must not mutate');
assert.throws(()=>placeCandidateDraft(layout,original.rows[0],[30,20]),/관·층/);
assert.throws(()=>placeCandidateDraft(mapped,original.rows.find(r=>r.shop_id==='h5-dolgorae'),[30,20]),/이미 위치/);
assert.throws(()=>placeCandidateDraft(layout,original.rows.find(r=>r.shop_id==='h5-dolgorae'),[200,20]),/좌표/);
const draft=prepareRegistryDraft(original);
assert.equal(draft.publication,'disabled');
assert.equal(draft.rows.length,14);
assert.ok(draft.rows.every(r=>r.verified===false));
console.log('PASS tenant onboarding: 14 photo-labelled shops, CSV quoted strings, conflicts, formula guard, draft polygons and approval hold');
